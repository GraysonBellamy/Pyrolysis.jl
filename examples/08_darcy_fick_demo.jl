"""
Darcy-Fick Gas Transport Demonstration

This example demonstrates the Darcy-Fick formulation for pressure-driven
gas transport during pyrolysis, comparing:
1. Diffusion-only transport (Fickian)
2. Full Darcy-Fick transport (advection + diffusion)

Physical Setup:
- Charring material under high heat flux (75 kW/m²)
- Solid matrix with low permeability
- Gas generated by decomposition creates internal pressure
- Pressure gradient drives bulk gas flow (Darcy flow)

Key Physics:
- Jⱼ = ξⱼ·v_g - Dⱼ,eff·∇ξⱼ   (Darcy-Fick flux)
- v_g = -(κ/μ)·∇P            (Darcy velocity)
- P = ξ_gas·R·T/M            (Ideal gas pressure)

Expected Observations:
- With Darcy flow: faster gas release, lower peak internal pressure
- Without Darcy flow: slower gas release, higher internal pressure buildup
- Both should conserve mass

Reference: ThermaKin2Ds equation 1.2 (gas transport)
"""

using Pyrolysis
using Printf

println("=" ^ 70)
println("Darcy-Fick Gas Transport Demonstration")
println("=" ^ 70)

# ============================================================================
# Material Definition: Charring Wood-like Material
# ============================================================================

println("\n1. Defining material...")

# Create a charring material with:
# 1. Virgin solid
# 2. Char residue
# 3. Pyrolysis gas

virgin = SolidComponent(:virgin,
	ρ = 500.0,      # kg/m³ - wood-like density
	c = 2000.0,     # J/(kg·K)
	k = 0.15,       # W/(m·K)
	ε = 0.9,        # emissivity
	α = 5.0,        # m²/kg - absorption coefficient
	κ = 1e-15,      # m² - low permeability (tight structure)
)

char = SolidComponent(:char,
	ρ = 150.0,      # kg/m³ - char is less dense
	c = 1500.0,     # J/(kg·K)
	k = 0.10,       # W/(m·K) - char is less conductive
	ε = 0.95,       # emissivity
	α = 50.0,       # m²/kg - char absorbs more radiation
	κ = 1e-12,      # m² - high permeability (porous char)
)

gas = GaseousComponent(:volatiles,
	M = 0.044,      # kg/mol - CO₂-like molecular weight
	c = 1200.0,     # J/(kg·K)
	k = 0.03,       # W/(m·K)
	λ = 2e-5,       # m²/s - diffusion coefficient
)

# Define decomposition reaction:
# virgin → 0.20 char + 0.80 gas (80% mass loss)
pyrolysis_reaction = Reaction(:pyrolysis, 1 => (2, 3),
	yields = (0.20, 0.80),    # 1 kg virgin → 0.2 kg char + 0.8 kg gas
	A = 1.0e13,       # s⁻¹ - pre-exponential factor
	E = 150e3,        # J/mol - activation energy (~150 kJ/mol)
	h = 300e3,        # J/kg - heat of reaction (endothermic)
	T_min = 400.0,    # K - reaction starts above 400 K
	T_max = 1500.0,    # K
)

# ============================================================================
# Component-Based Permeability for Darcy Flow
# ============================================================================

println("\n2. Component permeability configuration...")

# Permeability is now specified per component (κ parameter above):
# - Virgin: κ = 1e-15 m² (tight structure, low permeability)
# - Char:   κ = 1e-12 m² (porous, high permeability)
# - Gas:    No κ (gases flow THROUGH the matrix)
#
# Effective permeability is computed via mixing rules based on composition.
# As virgin converts to char, effective κ naturally increases.

println("   Virgin permeability: 1e-15 m² (tight structure)")
println("   Char permeability: 1e-12 m² (porous char)")
println("   Effective κ computed from composition via mixing rules")

# Create material - Darcy flow is automatically enabled when any component has κ > 0
material = Material(
	name = :CharringWood,
	components = (virgin, char, gas),
	reactions = (pyrolysis_reaction,),
	conductivity_mixing = PARALLEL,
	β = 0.5,
	permeability_mixing = WEIGHTED,    # Mix component permeabilities
	β_κ = 0.5,                          # 50/50 parallel/series mixing
)

println("   Material: $(material.name)")
println("   Components: virgin (κ=1e-15), char (κ=1e-12), volatiles (gas)")
println("   Reaction: virgin → 20% char + 80% gas")
println("   Darcy-Fick transport: enabled via component κ values")

# ============================================================================
# Mesh and Initial Conditions
# ============================================================================

println("\n3. Creating mesh...")

thickness = 0.010    # 10 mm sample
n_cells = 50
T_initial = 300.0    # K

# Initial concentrations: pure virgin material, no gas
ξ_virgin_initial = 500.0  # kg/m³
ξ_char_initial = 0.0
ξ_gas_initial = 0.0

mesh = create_uniform_mesh(thickness, n_cells, Val(3);
	T_initial = T_initial,
	ξ_initial = (ξ_virgin_initial, ξ_char_initial, ξ_gas_initial),
)

println("   Thickness: $(thickness*1000) mm")
println("   Cells: $n_cells")
println("   Initial T: $T_initial K")
println("   Initial virgin concentration: $ξ_virgin_initial kg/m³")

# ============================================================================
# Boundary Conditions
# ============================================================================

println("\n4. Setting boundary conditions...")

heat_flux = 75e3  # 75 kW/m² - high heat flux

# Create BoundaryConditionSet
bc_set = BoundaryConditionSet(
	thermal_top = HeatFluxBC(heat_flux) + RadiativeBC(ε = 0.9, T_inf = 300.0),  # Top: heat + reradiation
	thermal_bottom = AdiabaticBC(),  # Bottom: insulated
	mass_top = DiffusiveMassBC(0.01),  # Top: gas release
	mass_bottom = ImpermeableBC(),       # Bottom: impermeable
)

println("   Top surface: $(heat_flux/1000) kW/m² + reradiation")
println("   Bottom: adiabatic, impermeable")

# ============================================================================
# Problem Definition
# ============================================================================

println("\n5. Creating problem...")

tspan = (0.0, 120.0)  # 2 minutes
output_times = collect(0.0:10.0:120.0)

problem = PyrolysisProblem(
	mesh = mesh,
	material = material,
	bc_set = bc_set,
	T_initial = z -> T_initial,
	ξ_initial = [
		z -> ξ_virgin_initial,
		z -> ξ_char_initial,
		z -> ξ_gas_initial,
	],
	tspan = tspan,
	output_times = output_times,
)

println("   Time span: $(tspan[2]) s")
println("   Output times: every 10 s")

# ============================================================================
# Solve with Darcy-Fick Transport
# ============================================================================

println("\n6. Solving with Darcy-Fick transport...")
println("   (Darcy flow enabled via component κ values)")

solution_darcy = solve(problem;
	use_ale = true,
	min_thickness = 0.5e-3,   # 0.5 mm minimum
	dt_initial = 0.01,
	progress = true,
)

println("\n   Solution status: $(solution_darcy.retcode)")
println("   Final time: $(solution_darcy.times[end]) s")
println("   Final thickness: $(round(solution_darcy.thickness_history[end]*1000, digits=2)) mm")

# ============================================================================
# Results Analysis
# ============================================================================

println("\n7. Results Analysis")
println("-" ^ 50)

# Peak MLR
if !isempty(solution_darcy.mass_loss_rate)
	peak_mlr = maximum(solution_darcy.mass_loss_rate)
	peak_mlr_time = solution_darcy.time_fine[argmax(solution_darcy.mass_loss_rate)]
	println("   Peak MLR: $(round(peak_mlr*1000, digits=2)) g/(m²·s) at t=$(round(peak_mlr_time, digits=1)) s")
end

# Peak surface temperature
if !isempty(solution_darcy.surface_temperature)
	peak_T_surface = maximum(solution_darcy.surface_temperature)
	println("   Peak surface T: $(round(peak_T_surface, digits=0)) K")
end

# Mass conservation
initial_mass = solution_darcy.total_mass[1]
final_mass = solution_darcy.total_mass[end]
total_mass_released = initial_mass - final_mass
mass_conversion = (1 - final_mass/initial_mass) * 100

println("   Initial mass: $(round(initial_mass*1000, digits=2)) g/m²")
println("   Final mass: $(round(final_mass*1000, digits=2)) g/m²")
println("   Mass released: $(round(total_mass_released*1000, digits=2)) g/m² ($(round(mass_conversion, digits=1))%)")

# ============================================================================
# Summary
# ============================================================================

println("\n" * "=" ^ 70)
println("Darcy-Fick Demo Complete")
println("=" ^ 70)
println("""
Key observations:
- Darcy flow enables pressure-driven gas transport
- Gas escapes faster when permeability allows bulk flow
- Internal pressure gradients drive gas toward the surface
- Mass is conserved throughout the simulation
- Permeability evolves naturally as virgin wood converts to char

To compare with diffusion-only, create components with κ=0:
  # Components without permeability use diffusion-only transport
  virgin_diff = SolidComponent(:virgin, ρ=500, c=2000, k=0.15, κ=0.0)
  char_diff = SolidComponent(:char, ρ=150, c=1500, k=0.10, κ=0.0)
  material_diff = Material(components=(virgin_diff, char_diff, gas), ...)
  
  # Compare MLR curves - Darcy typically shows faster initial release
""")
