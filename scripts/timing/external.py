"""Time FDS, Gpyro V2 and ThermaKin2Ds on the matched comparison decks.

Every deck is regenerated by test/verification/reference/matched/run_comparisons.py
and must equal the committed input; every timed run's native outputs must equal
the committed outputs byte for byte (ThermaKin: without its start-date and
runtime lines, as committed). So each time belongs to exactly the computation
whose accuracy the comparison pages report.

Coarse configurations the matched study records as unavailable are skipped.

Protocol (see README.md): one pass over every configuration first (it warms the
binary and the page cache and sizes the repeats), then rounds of fresh processes,
each round over every configuration that still needs repeats, in alternating
order so drift spreads evenly. Repeats per configuration from the first pass:
5 if it took at most 30 s, 3 if at most 300 s, otherwise 1. Every run is one
process pinned by quiet.run_pinned; the first pass is recorded but not used.

    python3 scripts/timing/external.py OUTDIR --fds PATH --gpyro PATH --thermakin PATH \
        [--solvers fds,gpyro,thermakin] [--cases a,b] [--levels base,...] [--max-repeats 5]

Results are appended to OUTDIR/external_runs.jsonl (a rerun resumes) and
summarized in OUTDIR/external_summary.csv. Python 3.11+, standard library only.
"""

from pathlib import Path
import argparse
import csv
import gzip
import importlib.util
import os
import re
import shutil
import statistics
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parent))
import quiet  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
MATCHED = ROOT / "test" / "verification" / "reference" / "matched"
_spec = importlib.util.spec_from_file_location("run_comparisons", MATCHED / "run_comparisons.py")
rc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(rc)

SUCCESS = {
    "fds": "FDS completed successfully",
    "gpyro": "End of simulation reached successfully.",
    "thermakin": "Done",
}
TK_TIMING_LINES = ("Started on:", "Total runtime")


def repeats_for(seconds, cap):
    n = 5 if seconds <= 30 else 3 if seconds <= 300 else 1
    return min(n, cap)


# A configuration is (solver, case, level). For the matched decks `case` and
# `level` are run_comparisons.py's; level "committed" instead names a committed
# deck file by its path from the repository root, timed with its sibling
# outputs <stem>_*.csv as the identity check (--deck-runs).
COMMITTED = "committed"


def decks(solver, case, level):
    if level == COMMITTED:
        path = ROOT / case
        return {path.name: path.read_text()}
    p = rc.parameters(case)
    if solver == "thermakin":
        return {case + suffix: text for suffix, text in rc.thermakin(p, level).items()}
    ext = ".fds" if solver == "fds" else ".data"
    return {case + ext: (rc.fds if solver == "fds" else rc.gpyro)(p, level)}


def committed_dir(solver, case, level):
    if level == COMMITTED:
        return (ROOT / case).parent
    return MATCHED / "raw" / solver / level / case


def stem(case, level):
    return Path(case).stem if level == COMMITTED else case


def check_inputs(solver, case, level):
    """The regenerated decks must be the committed ones."""
    for name, text in decks(solver, case, level).items():
        committed = committed_dir(solver, case, level) / name
        if committed.read_text() != text:
            raise RuntimeError(f"{solver} {case} {level}: {name} differs from the committed deck")


def compare_outputs(solver, case, level, run_dir):
    """Names of committed native outputs the run did not reproduce exactly."""
    ref = committed_dir(solver, case, level)
    inputs = set(decks(solver, case, level)) | {"grid.json"}
    mismatched = []
    for f in sorted(ref.iterdir()):
        if f.name in inputs:
            continue
        if level == COMMITTED and not (f.name.startswith(stem(case, level) + "_")
                                       and f.suffix == ".csv"):
            continue
        if solver == "thermakin" and f.name.endswith(".out.gz"):
            new = run_dir / f.name[:-3]
            if not new.exists():
                mismatched.append(f.name)
                continue
            text = "".join(line for line in new.read_text().splitlines(keepends=True)
                           if not line.startswith(TK_TIMING_LINES))
            if gzip.decompress(f.read_bytes()).decode() != text:
                mismatched.append(f.name)
        else:
            new = run_dir / f.name
            if not new.exists() or new.read_bytes() != f.read_bytes():
                mismatched.append(f.name)
    return mismatched


def internal_seconds(solver, case, run_dir, log_text):
    """The solver's own elapsed-time report, where it prints one."""
    case = Path(case).stem
    if solver == "fds":
        text = (run_dir / f"{case}.out").read_text(errors="replace")
        m = re.search(r"Total Elapsed Wall Clock Time \(s\):\s*([0-9.Ee+-]+)", text)
        return float(m[1]) if m else None
    if solver == "thermakin":
        # "Total runtime [min]:" from a whole-second clock: recorded, but too
        # coarse to compare; analyze.py uses the process time for ThermaKin.
        for line in (run_dir / f"{case}.out").read_text(errors="replace").splitlines():
            if line.startswith("Total runtime"):
                m = re.search(r":\s*([0-9.]+(?:[Ee][+-]?[0-9]+)?)", line)
                scale = 60.0 if "[min]" in line else 1.0
                return float(m[1]) * scale if m else None
        return None
    m = re.findall(r"(?i)elapsed[^0-9]*([0-9]+\.[0-9]+)", log_text)
    return float(m[-1]) if m else None


def solver_env(solver, executable):
    env = {**os.environ, "OMP_NUM_THREADS": "1"}
    if solver == "fds":
        env["I_MPI_FABRICS"] = "shm"
        mpi = executable.parent / "intelmpi"
        if mpi.is_dir():
            env["LD_LIBRARY_PATH"] = str(mpi / "lib") + ":" + env.get("LD_LIBRARY_PATH", "")
            env["FI_PROVIDER_PATH"] = str(mpi / "prov")
    return env


def run_once(solver, executable, case, level, repeat, work, logs):
    run_dir = work / solver / level / case.replace("/", "__") / f"r{repeat}"
    shutil.rmtree(run_dir, ignore_errors=True)
    run_dir.mkdir(parents=True)
    for name, text in decks(solver, case, level).items():
        (run_dir / name).write_text(text)
    if solver == "thermakin":
        command = [str(executable)]
        stdin = f"{case}.cmp\n{case}.cnd\n{case}.out\n"  # matched decks only
    else:
        command = [str(executable), next(iter(decks(solver, case, level)))]
        stdin = None
    quiet.wait_quiet()
    log_path = run_dir / "run.log"
    rec = quiet.run_pinned(command, run_dir, log_path, env=solver_env(solver, executable),
                           stdin_text=stdin, timeout=4 * 3600)
    log_text = log_path.read_text(errors="replace")
    name = stem(case, level)
    banner = log_text if solver == "gpyro" else (run_dir / f"{name}.out").read_text(errors="replace")
    ok = (rec["returncode"] == 0 and SUCCESS[solver] in log_text
          and rc.VERSIONS[solver] in banner and "Error:" not in log_text)
    mismatched = compare_outputs(solver, case, level, run_dir) if ok else None
    row = dict(solver=solver, case=case, level=level, repeat=repeat, success=ok,
               outputs_identical=(mismatched == []), mismatched=mismatched,
               internal_s=internal_seconds(solver, case, run_dir, log_text) if ok else None,
               **rec)
    dest = logs / solver / level / case.replace("/", "__")
    dest.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(log_path, dest / f"r{repeat}.log")
    if solver != "gpyro" and (run_dir / f"{name}.out").exists():
        shutil.copyfile(run_dir / f"{name}.out", dest / f"r{repeat}.out")
    shutil.rmtree(run_dir, ignore_errors=True)
    return row


def summarize(rows, path):
    groups = {}
    for r in rows:
        groups.setdefault((r["solver"], r["case"], r["level"]), []).append(r)
    with open(path, "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["solver", "case", "level", "first_pass_s", "repeats", "median_s", "min_s",
                    "max_s", "median_user_s", "median_internal_s", "all_identical",
                    "max_sibling_busy", "max_others_busy", "max_involuntary_switches"])
        for (s, c, lv), rs in sorted(groups.items()):
            first = [r for r in rs if r["repeat"] == 0]
            timed = [r for r in rs if r["repeat"] > 0 and r["success"]]
            if not timed:
                w.writerow([s, c, lv, first[0]["wall_s"] if first else "", 0] + [""] * 9)
                continue
            walls = [r["wall_s"] for r in timed]
            internal = [r["internal_s"] for r in timed if r["internal_s"] is not None]
            w.writerow([
                s, c, lv, f"{first[0]['wall_s']:.6g}" if first else "", len(timed),
                f"{statistics.median(walls):.6g}", f"{min(walls):.6g}", f"{max(walls):.6g}",
                f"{statistics.median(r['user_s'] for r in timed):.6g}",
                f"{statistics.median(internal):.6g}" if internal else "",
                all(r["outputs_identical"] for r in timed),
                f"{max(r['sibling_busy'] for r in timed):.3f}",
                f"{max(r['others_busy'] for r in timed):.3f}",
                max(r["involuntary_switches"] for r in timed),
            ])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("outdir", type=Path)
    ap.add_argument("--fds", type=Path)
    ap.add_argument("--gpyro", type=Path)
    ap.add_argument("--thermakin", type=Path)
    ap.add_argument("--solvers", default="fds,gpyro,thermakin")
    ap.add_argument("--cases", default="all")
    ap.add_argument("--levels", default=",".join(rc.LEVELS))
    ap.add_argument("--max-repeats", type=int, default=5)
    ap.add_argument("--deck-runs", action="append", default=[],
                    help="SOLVER:GLOB of committed decks (from the repository root) to time "
                         "instead of the matched set, e.g. "
                         "fds:test/verification/reference/fds/custom/*.fds")
    ap.add_argument("--no-matched", action="store_true", help="time only --deck-runs")
    a = ap.parse_args()

    out = a.outdir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    work, logs = out / "work", out / "logs"
    results = out / "external_runs.jsonl"
    driver_cpus = quiet.keep_driver_off()
    env = quiet.environment()
    quiet.check_environment(env)

    solvers = a.solvers.split(",")
    executables = {s: getattr(a, s).resolve() for s in solvers}
    configs = []
    for s in solvers:
        if not executables[s].is_file():
            raise SystemExit(f"{s}: executable {executables[s]} not found")
        if a.no_matched:
            continue
        cases = rc.CASES[s] if a.cases == "all" else [c for c in a.cases.split(",") if c in rc.CASES[s]]
        for c in cases:
            for lv in a.levels.split(","):
                # A coarse configuration the study recorded as unavailable
                # has no committed run to time.
                if lv in rc.COARSE and not committed_dir(s, c, lv).is_dir():
                    continue
                check_inputs(s, c, lv)
                configs.append((s, c, lv))
    for spec in a.deck_runs:
        s, _, pattern = spec.partition(":")
        if s not in executables:
            raise SystemExit(f"--deck-runs {spec}: give --solvers {s} and its executable")
        found = sorted(ROOT.glob(pattern))
        if not found:
            raise SystemExit(f"--deck-runs {spec}: no decks")
        for deck in found:
            configs.append((s, str(deck.relative_to(ROOT)), COMMITTED))
    quiet.append_jsonl(out / "external_sessions.jsonl", dict(
        environment=env, driver_cpus=driver_cpus, repository=quiet.git_stamp(ROOT),
        generator_sha256=quiet.sha256(MATCHED / "run_comparisons.py"),
        executables={s: dict(path=str(p), sha256=quiet.sha256(p)) for s, p in executables.items()},
        configurations=len(configs), argv=sys.argv))

    done = {(r["solver"], r["case"], r["level"], r["repeat"]): r for r in quiet.read_jsonl(results)}

    def run(cfg, repeat):
        if (*cfg, repeat) in done:
            return done[(*cfg, repeat)]
        row = run_once(cfg[0], executables[cfg[0]], cfg[1], cfg[2], repeat, work, logs)
        row["time"] = time.strftime("%Y-%m-%dT%H:%M:%S")
        quiet.append_jsonl(results, row)
        done[(*cfg, repeat)] = row
        flag = "" if row["success"] and row["outputs_identical"] else "  <-- CHECK"
        print(f"{cfg[0]:9s} {cfg[1]:9s} {cfg[2]:12s} r{repeat} {row['wall_s']:10.4f} s "
              f"sib {row['sibling_busy']:.2f} oth {row['others_busy']:.2f}{flag}", flush=True)
        if not row["success"]:
            raise RuntimeError(f"{cfg}: unsuccessful run, see {logs}")
        return row

    first = {cfg: run(cfg, 0) for cfg in configs}
    need = {cfg: repeats_for(first[cfg]["wall_s"], a.max_repeats) for cfg in configs}
    estimate = sum(first[c]["wall_s"] * need[c] for c in configs)
    print(f"first pass done; timed rounds need about {estimate / 60:.1f} min", flush=True)
    for k in range(1, max(need.values(), default=0) + 1):
        order = [c for c in configs if need[c] >= k]
        for cfg in (order if k % 2 else reversed(order)):
            run(cfg, k)
    summarize(list(done.values()), out / "external_summary.csv")
    print(f"summary: {out / 'external_summary.csv'}", flush=True)


if __name__ == "__main__":
    main()
