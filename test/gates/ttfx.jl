# Time to first solve: the package's load time and the wall time of the first
# solve of each precompile workload, each in a fresh process, and of the
# Douglas fir deck of `examples/07_douglas_fir_cone.jl` over 60 s, whose
# material, property and boundary-condition types no workload shares. A
# workload's first solve measures what the package image caches; the Douglas
# fir deck measures the kernels a new problem compiles on top of the cached
# integrator.
#
# The environment must build the package with its precompile workloads (no
# `precompile_workloads = false` preference); the script refuses one that
# sets it. Each process runs `using Pyrolysis` (timed) and one solve (timed).
#
# Run from the repository root:
#   julia --project=ENV --startup-file=no ttfx.jl
# Writes measurements/ttfx.md.

include(joinpath(@__DIR__, "stamp.jl"))

const OUT = joinpath(@__DIR__, "measurements")
mkpath(OUT)
const ENV_DIR = dirname(Base.active_project())

function _preferences_off(dir)
    f = joinpath(dir, "LocalPreferences.toml")
    return isfile(f) && occursin(r"precompile_workloads\s*=\s*false", read(f, String))
end
_preferences_off(ENV_DIR) &&
    error("$(ENV_DIR) builds Pyrolysis without its precompile workloads")

# One fresh process: the load time and the first solve's wall time [s];
# `setup` runs between the two, untimed.
function _fresh(solve_expr::String; setup::String = "")
    code = """
    t_load = @elapsed using Pyrolysis
    $setup
    t_solve = @elapsed begin
        $solve_expr
    end
    println(t_load, " ", t_solve)
    """
    out = readchomp(`$(Base.julia_cmd()) --project=$ENV_DIR --startup-file=no -e $code`)
    load, solve = parse.(Float64, split(last(split(out, '\n'))))
    return load, solve
end

const IDENTITY = joinpath(@__DIR__, "burnout_identity.jl")

function main()
    names = let
        code = "using Pyrolysis; foreach(w -> println(first(w)), Pyrolysis._precompile_workloads())"
        split(
            readchomp(`$(Base.julia_cmd()) --project=$ENV_DIR --startup-file=no -e $code`),
        )
    end
    rows = Tuple{String,Float64,Float64}[]
    for (i, name) in enumerate(names)
        load, solve = _fresh("Pyrolysis._precompile_workloads()[$i][2]()")
        push!(rows, (String(name), load, solve))
        println(
            rpad(name, 52),
            round(load; digits = 2),
            " s load, ",
            round(solve; digits = 2),
            " s solve",
        )
        flush(stdout)
    end
    # The Douglas fir deck, built as the identity record builds it.
    setup = """
    include("$(escape_string(IDENTITY))")
    problem = douglas_fir_problem()
    """
    load, solve = _fresh("solve(problem)"; setup)
    push!(rows, ("Douglas fir deck, 60 s", load, solve))
    println(
        rpad("Douglas fir deck, 60 s", 52),
        round(load; digits = 2),
        " s load, ",
        round(solve; digits = 2),
        " s solve",
    )
    open(joinpath(OUT, "ttfx.md"), "w") do io
        println(io, "# Time to first solve\n")
        println(
            io,
            "Generated by `test/gates/ttfx.jl` at $(COMMIT_STAMP). Julia $(VERSION), ",
            "$(Sys.CPU_NAME), $(Sys.CPU_THREADS) threads. Each row is a fresh process: ",
            "the time of `using Pyrolysis` and of the first solve, the workload's own or ",
            "the Douglas fir deck's.\n",
        )
        println(io, "| configuration | load [s] | first solve [s] |")
        println(io, "|---|---|---|")
        for (name, load, solve) in rows
            println(
                io,
                "| ",
                name,
                " | ",
                round(load; digits = 2),
                " | ",
                round(solve; digits = 2),
                " |",
            )
        end
    end
    return rows
end

main()
