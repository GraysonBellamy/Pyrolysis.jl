"""
Gas Transport Formulation: First-Principles Derivation and Quantitative Test
=============================================================================

This file derives the correct diffusive gas transport equation for pyrolysis
from first principles and tests two candidate formulations numerically.

PHYSICAL SETUP
--------------
A porous solid material with gas filling the pore space.
- Gas is generated by decomposition reactions within the solid.
- Gas species have mass concentration ξ [kg/m³] (mass per unit total volume).
- The solid matrix has a transport coefficient λ [m²/s].
- Temperature varies spatially.
- Gas obeys ideal gas law: ρ_gas = P*M/(R*T) where M is molar mass.

TWO CANDIDATE FORMULATIONS
---------------------------
Formulation A (mass fraction gradient):
    J_A = -λ * ρ_mix * ∂(ξ/ρ_mix)/∂x

Formulation B (volume fraction gradient):
    J_B = -λ * ρ_gas * ∂(ξ/ρ_gas)/∂x

where:
    ρ_mix = mixture density (from equation of state with swelling)
    ρ_gas = pure gas density from ideal gas law = P*M/(R*T)


================================================================================
PART 1: DERIVATION FROM FICK'S LAW
================================================================================

Fick's law in its fundamental form states that diffusion is driven by the
gradient of a POTENTIAL that equalizes at equilibrium. For an ideal gas
mixture at constant temperature and pressure, this is the mole fraction
gradient (or equivalently, the partial pressure gradient).

For a single gas species in a porous solid matrix, we must identify the
correct analog of "mole fraction" or "partial pressure."

KEY INSIGHT: The gas occupies the PORE SPACE of the solid. The natural
measure of gas content that determines diffusion is the gas partial pressure,
which for an ideal gas at constant total pressure is proportional to the
mole fraction (or volume fraction) within the gas phase.

Volume fraction of gas species in the pore space:
    φ_gas = ξ / ρ_gas

where ρ_gas(T) = P*M/(R*T) is the density of the pure gas at the local
temperature and pressure. This φ_gas represents what fraction of the
available volume is occupied by this gas species.

Mass fraction in the total mixture:
    Y = ξ / ρ_mix

where ρ_mix depends on ALL components (solid + gas).


================================================================================
PART 2: ALGEBRAIC EXPANSION
================================================================================

FORMULATION A: J_A = -λ ρ_mix ∂(ξ/ρ_mix)/∂x

Expand the derivative using the quotient rule:
    ∂(ξ/ρ_mix)/∂x = (1/ρ_mix) ∂ξ/∂x - (ξ/ρ_mix²) ∂ρ_mix/∂x

Therefore:
    J_A = -λ ρ_mix [(1/ρ_mix) ∂ξ/∂x - (ξ/ρ_mix²) ∂ρ_mix/∂x]
        = -λ ∂ξ/∂x + λ (ξ/ρ_mix) ∂ρ_mix/∂x
        = -λ ∂ξ/∂x + λ Y ∂ρ_mix/∂x

    J_A = -λ [∂ξ/∂x - Y ∂ρ_mix/∂x]                              ... (A)

The additional term λ Y ∂ρ_mix/∂x depends on gradients of the MIXTURE
density. In a porous medium, ρ_mix changes due to:
(a) solid density changes (decomposition, charring),
(b) gas content changes,
(c) temperature-dependent gas density.

The problem: ∂ρ_mix/∂x depends on ALL components, not just the gas.
If the solid structure is uniform but T varies, ρ_mix changes because gas
density changes with T. But ρ_mix also changes when solid decomposition
creates local composition gradients. This couples the gas transport to
solid state changes in a non-physical way.

FORMULATION B: J_B = -λ ρ_gas ∂(ξ/ρ_gas)/∂x

Expand the derivative using the quotient rule:
    ∂(ξ/ρ_gas)/∂x = (1/ρ_gas) ∂ξ/∂x - (ξ/ρ_gas²) ∂ρ_gas/∂x

Therefore:
    J_B = -λ ρ_gas [(1/ρ_gas) ∂ξ/∂x - (ξ/ρ_gas²) ∂ρ_gas/∂x]
        = -λ ∂ξ/∂x + λ (ξ/ρ_gas) ∂ρ_gas/∂x

Now, for an ideal gas at constant pressure:
    ρ_gas = P*M/(R*T)
    ∂ρ_gas/∂x = -P*M/(R*T²) ∂T/∂x = -(ρ_gas/T) ∂T/∂x

Substituting:
    J_B = -λ ∂ξ/∂x + λ (ξ/ρ_gas) × [-(ρ_gas/T) ∂T/∂x]
        = -λ ∂ξ/∂x - λ (ξ/T) ∂T/∂x

    J_B = -λ [∂ξ/∂x + (ξ/T) ∂T/∂x]                              ... (B)

The additional term -λ(ξ/T)∂T/∂x is a THERMAL DIFFUSION term. It
drives gas from hot regions to cold regions (down the temperature
gradient), which is physically correct: at equal mass concentration ξ,
the hot side has HIGHER partial pressure (ideal gas: p = ξRT/M),
so gas should flow toward the cold side.

EQUIVALENT FORM OF B:
Note that ∂(ξ/ρ_gas)/∂x = ∂(ξ R T / (P M))/∂x. For constant P, M:
    ∂(ξ T)/∂x = T ∂ξ/∂x + ξ ∂T/∂x

So:
    J_B = -λ (1/T) [T ∂ξ/∂x + ξ ∂T/∂x] = -(λ/T) ∂(ξT)/∂x

Or equivalently, since partial pressure p = ξRT/M:
    J_B = -(λ M)/(R T) ∂p/∂x

This is precisely Darcy/Fick transport driven by PARTIAL PRESSURE gradient,
which is thermodynamically correct.


================================================================================
PART 3: PHYSICAL MEANING - WHAT IS THE DRIVING FORCE?
================================================================================

(a) Mass fraction gradient (∂Y/∂x where Y = ξ/ρ_mix):
    This measures the fraction of the total mixture that is gas. But in a
    porous medium with a rigid solid skeleton, the solid density is
    irrelevant to gas transport. Two cells with the same gas partial
    pressure but different solid content would have different Y values,
    creating a spurious flux. Mass fraction is the correct driving force
    for diffusion in a FLUID MIXTURE (two miscible fluids), not for gas
    transport through a POROUS SOLID MATRIX.

(b) Volume fraction gradient (∂φ/∂x where φ = ξ/ρ_gas):
    This measures the fraction of the pore space filled by this gas
    species. For an ideal gas at constant pressure, φ is proportional
    to the partial pressure. This is physically appropriate because
    gas molecules diffuse through the pore network, and the relevant
    concentration is the gas-phase concentration, not the fraction of
    the total (solid+gas) mixture.

(c) Partial pressure gradient:
    For ideal gas, p = ξRT/M. The partial pressure gradient is the
    fundamental thermodynamic driving force. Formulation B is exactly
    proportional to ∂p/∂x (shown above), while Formulation A is not.

(d) Chemical potential gradient:
    For an ideal gas, μ = μ₀ + RT ln(p/p₀). The gradient of chemical
    potential is (RT/p)∂p/∂x, proportional to ∂(ln p)/∂x. Both the
    partial pressure and chemical potential gradients point the same
    direction. Formulation B captures this correctly.

CONCLUSION: Formulation B (volume fraction / partial pressure gradient)
is the physically correct formulation for gas transport in porous media.


================================================================================
PART 4: LIMITING CASES
================================================================================

Case 1: Uniform temperature (∂T/∂x = 0)
    Formulation A: J_A = -λ ∂ξ/∂x + λ Y ∂ρ_mix/∂x
    Formulation B: J_B = -λ ∂ξ/∂x

    If T is uniform AND solid composition is uniform, then ∂ρ_mix/∂x
    depends only on ∂ξ/∂x. In this special case the formulations may
    approximately agree but NOT exactly, because ∂ρ_mix/∂x involves
    the equation of state coupling.

    For dilute gas (ξ << ξ_solid), Y ≈ 0 and the correction in A is
    small. They agree in the dilute limit at uniform T.

Case 2: Pure gas (no solid, ξ_solid = 0)
    ρ_mix = ρ_gas (if γ=1 for gas, the mixture density equals gas density).
    Formulation A: J_A = -λ ρ_gas ∂(ξ/ρ_gas)/∂x = J_B
    They AGREE when there is no solid.

Case 3: Rigid porous medium (γ=0 for gas, solid dominates volume)
    ρ_mix ≈ 1/Σ(Y_solid/ρ_solid) — dominated by solid contribution.
    Formulation A: The driving force ∂Y/∂x is contaminated by ρ_mix
        changes from the solid composition, not from gas behavior.
    Formulation B: The driving force ∂(ξ/ρ_gas)/∂x = (M/PRT)∂p/∂x
        is proportional to the partial pressure gradient, consistent
        with Darcy's law: v = -(κ/μ)∂P/∂x.
    Formulation B correctly reduces to partial-pressure-driven transport.

Case 4: Fully expanding medium (γ=1 for gas, gas volume contributes)
    Now gas volume contributes to the mixture volume. For a PURE gas
    system, this reduces to ordinary diffusion:
    ρ_mix ≈ ρ_gas (for dilute solid), and both formulations agree.
    For a mixture, Formulation B still uses the correct gas-phase
    driving force, while A conflates gas and solid contributions.

SUMMARY: Formulation B is correct in ALL cases. Formulation A agrees
with B only in special cases (uniform T, pure gas, dilute gas).


================================================================================
PART 5: QUANTITATIVE NUMERICAL TEST
================================================================================
"""

using Test

# Physical constants
const R_gas = 8.31446261815324  # J/(mol·K)
const P_atm = 101325.0         # Pa

@testset "Gas Transport Formulation Derivation" begin

    # ========================================================================
    # Problem Setup
    # ========================================================================
    # Two cells at different temperatures, SAME gas mass concentration
    T_L = 400.0   # K (left cell)
    T_R = 800.0   # K (right cell)
    ξ_gas_L = 10.0   # kg/m³ gas mass concentration (left)
    ξ_gas_R = 10.0   # kg/m³ gas mass concentration (right)
    ξ_solid = 500.0  # kg/m³ solid mass concentration (both cells)
    M_gas = 0.028    # kg/mol (N₂-like gas)
    λ = 1e-5         # m²/s transport coefficient
    Δx = 1e-3        # m cell spacing

    # Gas densities from ideal gas law: ρ_gas = P*M/(R*T)
    ρ_gas_L = P_atm * M_gas / (R_gas * T_L)
    ρ_gas_R = P_atm * M_gas / (R_gas * T_R)

    @testset "Ideal gas densities" begin
        @test ρ_gas_L ≈ 0.8530 atol=0.001
        @test ρ_gas_R ≈ 0.4265 atol=0.001
        # Hot side has half the gas density
        @test ρ_gas_L / ρ_gas_R ≈ T_R / T_L  # = 2.0
    end

    # ========================================================================
    # Partial pressures (the REAL driving force)
    # ========================================================================
    # For ideal gas: p = ξ * R * T / M
    p_L = ξ_gas_L * R_gas * T_L / M_gas
    p_R = ξ_gas_R * R_gas * T_R / M_gas

    @testset "Partial pressures differ despite equal ξ" begin
        @test p_L ≈ 1.188e6 rtol=0.01
        @test p_R ≈ 2.376e6 rtol=0.01
        # Right side has DOUBLE the partial pressure!
        @test p_R / p_L ≈ T_R / T_L  # = 2.0
        # Gas should flow from RIGHT (high p) to LEFT (low p)
        # i.e., flux should be NEGATIVE (right to left = -x direction)
    end

    # ========================================================================
    # Volume fractions (pore space filling)
    # ========================================================================
    φ_L = ξ_gas_L / ρ_gas_L  # volume fraction at left
    φ_R = ξ_gas_R / ρ_gas_R  # volume fraction at right

    @testset "Volume fractions differ despite equal ξ" begin
        @test φ_L ≈ 11.72 rtol=0.01
        @test φ_R ≈ 23.44 rtol=0.01
        # Right side has double the volume fraction (hotter gas is less dense,
        # so the same mass occupies more volume)
        @test φ_R / φ_L ≈ T_R / T_L  # = 2.0
    end

    # ========================================================================
    # Mixture densities (depends on swelling factor γ)
    # ========================================================================
    # For γ = 0 (rigid matrix, gas does NOT contribute to volume):
    #   1/ρ_mix = Y_solid/ρ_solid_pure
    #   This simplifies: ρ_mix = ξ_solid + ξ_gas (total mass concentration)
    #   BUT the specific volume is just Y_solid/ρ_solid_pure = (ξ_solid/ρ_total)/ρ_solid_pure
    #   Actually for γ=0: 1/ρ_mix = Σ_solid(Y_j/ρ_j) + 0 (gas terms zeroed)
    #   With one solid at fixed density ρ_s:
    #   1/ρ_mix = Y_solid/ρ_s = (ξ_solid/(ξ_solid+ξ_gas))/ρ_s
    #   ρ_mix = ρ_s(ξ_solid+ξ_gas)/ξ_solid

    # Using γ=0 (standard for gas in rigid porous medium)
    ρ_solid_pure = 1000.0  # intrinsic solid density [kg/m³]

    # Total mass concentration
    ρ_total_L = ξ_solid + ξ_gas_L  # = 510 kg/m³
    ρ_total_R = ξ_solid + ξ_gas_R  # = 510 kg/m³

    # Mixture density with γ=0:
    # 1/ρ_mix = Y_solid/ρ_solid_pure (gas volume fraction zeroed out)
    Y_solid_L = ξ_solid / ρ_total_L
    Y_solid_R = ξ_solid / ρ_total_R
    ρ_mix_L = 1.0 / (Y_solid_L / ρ_solid_pure)
    ρ_mix_R = 1.0 / (Y_solid_R / ρ_solid_pure)

    @testset "Mixture densities (γ=0)" begin
        # With equal ξ_gas and ξ_solid, ρ_mix should be equal in both cells
        @test ρ_mix_L ≈ ρ_mix_R
        # ρ_mix = ρ_solid_pure * ρ_total / ξ_solid = 1000 * 510/500 = 1020
        @test ρ_mix_L ≈ 1020.0
    end

    # ========================================================================
    # Formulation A: J = -λ * ρ_mix * ∂(ξ/ρ_mix)/∂x
    # ========================================================================
    Y_gas_L = ξ_gas_L / ρ_mix_L  # mass fraction of gas in mixture
    Y_gas_R = ξ_gas_R / ρ_mix_R

    # Face value of ρ_mix (arithmetic mean)
    ρ_mix_face = 0.5 * (ρ_mix_L + ρ_mix_R)

    # Flux
    J_A = -λ * ρ_mix_face * (Y_gas_R - Y_gas_L) / Δx

    @testset "Formulation A: mass fraction gradient" begin
        # With equal ρ_mix on both sides and equal ξ_gas:
        # Y_gas_L = Y_gas_R = 10/1020 ≈ 0.00980
        @test Y_gas_L ≈ Y_gas_R
        # Therefore: ΔY = 0 → J_A = 0!
        @test J_A ≈ 0.0 atol=1e-15

        println("\n=== Formulation A: J = -λ ρ_mix ∂Y/∂x ===")
        println("  Y_gas_L = ξ_gas/ρ_mix = $(ξ_gas_L)/$(ρ_mix_L) = $(Y_gas_L)")
        println("  Y_gas_R = ξ_gas/ρ_mix = $(ξ_gas_R)/$(ρ_mix_R) = $(Y_gas_R)")
        println("  ΔY = $(Y_gas_R - Y_gas_L)")
        println("  J_A = $J_A kg/(m²·s)")
        println("  → PREDICTS ZERO FLUX despite 2× pressure difference!")
    end

    # ========================================================================
    # Formulation B: J = -λ * ρ_gas * ∂(ξ/ρ_gas)/∂x
    # ========================================================================
    φ_gas_L = ξ_gas_L / ρ_gas_L  # volume fraction (= ξRT/(PM))
    φ_gas_R = ξ_gas_R / ρ_gas_R

    # Face value of ρ_gas (harmonic mean for diffusion-like coefficient)
    ρ_gas_face = 2.0 * ρ_gas_L * ρ_gas_R / (ρ_gas_L + ρ_gas_R)

    # Flux
    J_B = -λ * ρ_gas_face * (φ_gas_R - φ_gas_L) / Δx

    @testset "Formulation B: volume fraction gradient" begin
        # φ differs because ρ_gas differs (temperature-dependent):
        @test φ_gas_R ≈ 2.0 * φ_gas_L rtol=0.01
        # Δφ > 0, so flux is NEGATIVE (left-pointing) = gas flows from hot to cold
        @test J_B < 0.0

        println("\n=== Formulation B: J = -λ ρ_gas ∂φ/∂x ===")
        println("  φ_L = ξ/ρ_gas = $(ξ_gas_L)/$(round(ρ_gas_L,digits=4)) = $(round(φ_gas_L,digits=4))")
        println("  φ_R = ξ/ρ_gas = $(ξ_gas_R)/$(round(ρ_gas_R,digits=4)) = $(round(φ_gas_R,digits=4))")
        println("  Δφ = $(round(φ_gas_R - φ_gas_L,digits=4))")
        println("  ρ_gas_face (harmonic) = $(round(ρ_gas_face,digits=6))")
        println("  J_B = $(round(J_B, sigdigits=6)) kg/(m²·s)")
        println("  → PREDICTS NON-ZERO FLUX: gas flows from high-p (hot) to low-p (cold)")
    end

    # ========================================================================
    # Verify Formulation B equals partial-pressure-driven flux
    # ========================================================================
    # From the derivation: J_B = -(λ M)/(R T_face) × ∂p/∂x
    # where T_face is some average temperature.
    # More directly: J_B = -λ ρ_gas_face × Δφ/Δx
    #              = -λ ρ_gas_face × (ξ_R/ρ_gas_R - ξ_L/ρ_gas_L) / Δx

    # Equivalent: since φ = ξRT/(PM), Δφ = (R/(PM))(ξ_R T_R - ξ_L T_L)
    # and ρ_gas_face (harmonic) = 2(PM)²/(R²T_LT_R) / [(PM)(T_L+T_R)/(RT_LT_R)]
    #                           = 2PM / [R(T_L+T_R)]
    # Therefore:
    # J_B = -λ × [2PM/(R(T_L+T_R))] × [R/(PM)] × Δ(ξT) / Δx
    #     = -λ × 2/(T_L+T_R) × Δ(ξT)/Δx
    #     = -(λ/T_face_arith) × Δ(ξT)/Δx
    # where T_face_arith = (T_L+T_R)/2 is the ARITHMETIC mean.

    T_face_arith_eq = 0.5 * (T_L + T_R)
    J_B_via_ξT = -(λ / T_face_arith_eq) * (ξ_gas_R * T_R - ξ_gas_L * T_L) / Δx

    @testset "Formulation B equivalence with ∂(ξT)/∂x" begin
        @test J_B ≈ J_B_via_ξT rtol=1e-10
        println("\n=== Equivalence check ===")
        println("  J_B (via volume fraction) = $(round(J_B, sigdigits=6))")
        println("  J_B (via ξT gradient)     = $(round(J_B_via_ξT, sigdigits=6))")
        println("  Match: $(isapprox(J_B, J_B_via_ξT, rtol=1e-10))")
    end

    # ========================================================================
    # Expanded form: verify thermal diffusion term
    # ========================================================================
    # From the derivation:
    # J_B = -λ [∂ξ/∂x + (ξ/T)∂T/∂x]
    #
    # With uniform ξ: ∂ξ/∂x = 0
    # So: J_B = -λ (ξ/T_face) ∂T/∂x

    ξ_face = 0.5 * (ξ_gas_L + ξ_gas_R)  # = 10 since both equal
    T_face_arith = 0.5 * (T_L + T_R)
    ∂T_∂x = (T_R - T_L) / Δx
    ∂ξ_∂x = (ξ_gas_R - ξ_gas_L) / Δx  # = 0

    J_B_expanded = -λ * (∂ξ_∂x + (ξ_face / T_face_arith) * ∂T_∂x)

    @testset "Thermal diffusion term" begin
        @test ∂ξ_∂x ≈ 0.0
        @test ∂T_∂x ≈ 4e5  # 400K / 1mm

        # The thermal diffusion term:
        thermal_term = -λ * (ξ_face / T_face_arith) * ∂T_∂x
        @test thermal_term < 0.0  # gas flows from hot to cold

        println("\n=== Expanded Formulation B ===")
        println("  J_B = -λ [∂ξ/∂x + (ξ/T) ∂T/∂x]")
        println("  ∂ξ/∂x = $∂ξ_∂x (zero — same concentration both sides)")
        println("  ∂T/∂x = $∂T_∂x K/m")
        println("  Fickian term: -λ ∂ξ/∂x = $(round(-λ * ∂ξ_∂x, sigdigits=4))")
        println("  Thermal term: -λ(ξ/T)∂T/∂x = $(round(thermal_term, sigdigits=6))")
        println("  J_B_expanded = $(round(J_B_expanded, sigdigits=6))")
    end

    # ========================================================================
    # Expanded form of A: verify ∂ρ_mix/∂x term
    # ========================================================================
    # J_A = -λ [∂ξ/∂x - Y ∂ρ_mix/∂x]
    ∂ρ_mix_∂x = (ρ_mix_R - ρ_mix_L) / Δx
    Y_face = 0.5 * (Y_gas_L + Y_gas_R)
    J_A_expanded = -λ * (∂ξ_∂x - Y_face * ∂ρ_mix_∂x)

    @testset "Formulation A expanded form" begin
        # With γ=0 and uniform solid, ρ_mix is the same in both cells
        @test ∂ρ_mix_∂x ≈ 0.0 atol=1e-10
        @test J_A_expanded ≈ 0.0 atol=1e-15

        println("\n=== Expanded Formulation A ===")
        println("  J_A = -λ [∂ξ/∂x - Y ∂ρ_mix/∂x]")
        println("  ∂ξ/∂x = $∂ξ_∂x")
        println("  ∂ρ_mix/∂x = $∂ρ_mix_∂x")
        println("  Fickian term: -λ ∂ξ/∂x = 0")
        println("  ρ_mix correction: λ Y ∂ρ_mix/∂x = 0")
        println("  J_A = $J_A_expanded")
        println("  → Formulation A MISSES the thermal diffusion entirely!")
    end

    # ========================================================================
    # Summary comparison
    # ========================================================================
    @testset "Key result: formulations disagree when T varies" begin
        println("\n" * "="^70)
        println("SUMMARY: Two cells with identical ξ_gas = $(ξ_gas_L) kg/m³")
        println("  T_L = $(T_L)K, T_R = $(T_R)K")
        println("  Partial pressure ratio: p_R/p_L = $(p_R/p_L)")
        println()
        println("  Formulation A (mass fraction):  J = $(round(J_A, sigdigits=4)) kg/(m²·s)")
        println("  Formulation B (volume fraction): J = $(round(J_B, sigdigits=6)) kg/(m²·s)")
        println()
        println("  Physical expectation: Gas should flow from high pressure")
        println("  (hot side) to low pressure (cold side) → J < 0")
        println()
        println("  Formulation A gives ZERO flux → INCORRECT")
        println("  Formulation B gives negative flux → CORRECT")
        println("="^70)

        # A predicts zero flux
        @test abs(J_A) < 1e-15
        # B predicts nonzero flux in the correct direction
        @test J_B < 0.0
        @test abs(J_B) > 0.01  # substantial flux
    end

    # ========================================================================
    # Limiting case 1: Uniform temperature
    # ========================================================================
    @testset "Limiting case: uniform temperature" begin
        T_uniform = 600.0  # K
        ξ_L_case = 15.0    # kg/m³
        ξ_R_case = 5.0     # kg/m³

        ρ_gas_uniform = P_atm * M_gas / (R_gas * T_uniform)
        ρ_total_L_case = ξ_solid + ξ_L_case
        ρ_total_R_case = ξ_solid + ξ_R_case

        # γ=0 mixture density
        ρ_mix_L_case = ρ_solid_pure * ρ_total_L_case / ξ_solid
        ρ_mix_R_case = ρ_solid_pure * ρ_total_R_case / ξ_solid

        # Formulation A
        Y_L_case = ξ_L_case / ρ_mix_L_case
        Y_R_case = ξ_R_case / ρ_mix_R_case
        ρ_mix_face_case = 0.5 * (ρ_mix_L_case + ρ_mix_R_case)
        J_A_case = -λ * ρ_mix_face_case * (Y_R_case - Y_L_case) / Δx

        # Formulation B
        φ_L_case = ξ_L_case / ρ_gas_uniform
        φ_R_case = ξ_R_case / ρ_gas_uniform
        J_B_case = -λ * ρ_gas_uniform * (φ_R_case - φ_L_case) / Δx

        # Simple Fick: J = -λ ∂ξ/∂x
        J_fick = -λ * (ξ_R_case - ξ_L_case) / Δx

        println("\n=== Limiting case: Uniform T = $(T_uniform)K ===")
        println("  ξ_L = $ξ_L_case, ξ_R = $ξ_R_case kg/m³")
        println("  J_A = $(round(J_A_case, sigdigits=6)) kg/(m²·s)")
        println("  J_B = $(round(J_B_case, sigdigits=6)) kg/(m²·s)")
        println("  J_fick = $(round(J_fick, sigdigits=6)) kg/(m²·s)")

        # At uniform T, Formulation B reduces to simple Fick's law:
        # J_B = -λ ρ_gas Δ(ξ/ρ_gas)/Δx = -λ Δξ/Δx (since ρ_gas cancels)
        @test J_B_case ≈ J_fick rtol=1e-10

        # Formulation A does NOT reduce to simple Fick's law because
        # ρ_mix differs on the two sides (different gas content):
        println("  ρ_mix_L = $(round(ρ_mix_L_case, digits=2))")
        println("  ρ_mix_R = $(round(ρ_mix_R_case, digits=2))")
        println("  → ρ_mix differs ⇒ Formulation A ≠ simple Fick's law")

        # Both should predict gas flowing from high-ξ to low-ξ side
        @test J_A_case > 0.0
        @test J_B_case > 0.0

        # But they differ quantitatively due to ρ_mix coupling:
        relative_diff = abs(J_A_case - J_B_case) / abs(J_B_case)
        println("  Relative difference: $(round(100*relative_diff, digits=2))%")
        # The difference is small but nonzero
        @test relative_diff > 0.0
    end

    # ========================================================================
    # Limiting case 2: Pure gas (no solid)
    # ========================================================================
    @testset "Limiting case: pure gas (no solid)" begin
        T_L_pg = 400.0
        T_R_pg = 800.0
        ξ_L_pg = 10.0
        ξ_R_pg = 10.0
        ξ_solid_pg = 0.0  # No solid!

        ρ_gas_L_pg = P_atm * M_gas / (R_gas * T_L_pg)
        ρ_gas_R_pg = P_atm * M_gas / (R_gas * T_R_pg)

        # With no solid and γ=1 for gas, ρ_mix = ρ_gas
        # 1/ρ_mix = Y_gas/ρ_gas = (ξ_gas/(ξ_gas))/ρ_gas = 1/ρ_gas
        ρ_mix_L_pg = ρ_gas_L_pg
        ρ_mix_R_pg = ρ_gas_R_pg

        # Formulation A with ρ_mix = ρ_gas
        Y_L_pg = ξ_L_pg / ρ_mix_L_pg
        Y_R_pg = ξ_R_pg / ρ_mix_R_pg
        ρ_mix_face_pg = 0.5 * (ρ_mix_L_pg + ρ_mix_R_pg)
        J_A_pg = -λ * ρ_mix_face_pg * (Y_R_pg - Y_L_pg) / Δx

        # Formulation B
        φ_L_pg = ξ_L_pg / ρ_gas_L_pg
        φ_R_pg = ξ_R_pg / ρ_gas_R_pg
        ρ_gas_face_pg = 2.0 * ρ_gas_L_pg * ρ_gas_R_pg / (ρ_gas_L_pg + ρ_gas_R_pg)
        J_B_pg = -λ * ρ_gas_face_pg * (φ_R_pg - φ_L_pg) / Δx

        println("\n=== Limiting case: Pure gas (no solid) ===")
        println("  J_A = $(round(J_A_pg, sigdigits=6))")
        println("  J_B = $(round(J_B_pg, sigdigits=6))")

        # When ρ_mix = ρ_gas (pure gas, γ=1), the formulations agree
        # up to the face interpolation scheme:
        # J_A uses arithmetic mean of ρ_mix, J_B uses harmonic mean of ρ_gas
        # With arithmetic mean for A:
        J_A_harmonic = -λ * ρ_gas_face_pg * (Y_R_pg - Y_L_pg) / Δx

        # Y = ξ/ρ_gas = φ when ρ_mix = ρ_gas, so same gradient
        @test Y_L_pg ≈ φ_L_pg rtol=1e-10
        @test Y_R_pg ≈ φ_R_pg rtol=1e-10

        # With same face interpolation, they agree exactly:
        @test J_A_harmonic ≈ J_B_pg rtol=1e-10
        println("  With same face interpolation: J_A ≈ J_B ✓")
    end

    # ========================================================================
    # Limiting case 3: Dense solid, dilute gas (γ=0)
    # ========================================================================
    @testset "Limiting case: dense solid, dilute gas (Darcy-like)" begin
        # Rigid porous medium — solid dominates, gas is dilute
        ξ_solid_dense = 2000.0  # kg/m³
        ξ_gas_dilute = 0.1      # kg/m³
        T_L_d = 500.0
        T_R_d = 1000.0

        ρ_gas_L_d = P_atm * M_gas / (R_gas * T_L_d)
        ρ_gas_R_d = P_atm * M_gas / (R_gas * T_R_d)

        # Partial pressures
        p_L_d = ξ_gas_dilute * R_gas * T_L_d / M_gas
        p_R_d = ξ_gas_dilute * R_gas * T_R_d / M_gas

        # γ=0 mixture density (gas doesn't contribute to volume)
        ρ_total_L_d = ξ_solid_dense + ξ_gas_dilute
        ρ_total_R_d = ξ_solid_dense + ξ_gas_dilute
        ρ_mix_L_d = ρ_solid_pure * ρ_total_L_d / ξ_solid_dense
        ρ_mix_R_d = ρ_solid_pure * ρ_total_R_d / ξ_solid_dense

        # Formulation B (partial pressure driven)
        φ_L_d = ξ_gas_dilute / ρ_gas_L_d
        φ_R_d = ξ_gas_dilute / ρ_gas_R_d
        ρ_gas_face_d = 2.0 * ρ_gas_L_d * ρ_gas_R_d / (ρ_gas_L_d + ρ_gas_R_d)
        J_B_d = -λ * ρ_gas_face_d * (φ_R_d - φ_L_d) / Δx

        # Formulation A (mass fraction driven)
        Y_L_d = ξ_gas_dilute / ρ_mix_L_d
        Y_R_d = ξ_gas_dilute / ρ_mix_R_d
        ρ_mix_face_d = 0.5 * (ρ_mix_L_d + ρ_mix_R_d)
        J_A_d = -λ * ρ_mix_face_d * (Y_R_d - Y_L_d) / Δx

        # Darcy flux: J_Darcy ∝ -∂p/∂x
        Δp = p_R_d - p_L_d

        println("\n=== Limiting case: Dense solid, dilute gas ===")
        println("  p_L = $(round(p_L_d, sigdigits=4)) Pa")
        println("  p_R = $(round(p_R_d, sigdigits=4)) Pa")
        println("  Δp = $(round(Δp, sigdigits=4)) Pa")
        println("  J_A = $(round(J_A_d, sigdigits=6))")
        println("  J_B = $(round(J_B_d, sigdigits=6))")

        # B captures pressure gradient; A gives zero (same ξ, same ρ_mix)
        @test abs(J_A_d) < 1e-15  # zero!
        @test J_B_d < 0.0         # correct direction (high p to low p)
        println("  Formulation B aligns with Darcy's law (∝ -∂p/∂x)")
        println("  Formulation A gives zero → inconsistent with Darcy's law")
    end

    # ========================================================================
    # Case where ξ differs AND T differs — both terms active
    # ========================================================================
    @testset "Combined ξ and T gradients" begin
        T_L_c = 400.0
        T_R_c = 800.0
        ξ_L_c = 15.0   # higher concentration on cold side
        ξ_R_c = 5.0    # lower concentration on hot side

        ρ_gas_L_c = P_atm * M_gas / (R_gas * T_L_c)
        ρ_gas_R_c = P_atm * M_gas / (R_gas * T_R_c)

        # Partial pressures
        p_L_c = ξ_L_c * R_gas * T_L_c / M_gas
        p_R_c = ξ_R_c * R_gas * T_R_c / M_gas

        # Volume fractions
        φ_L_c = ξ_L_c / ρ_gas_L_c
        φ_R_c = ξ_R_c / ρ_gas_R_c

        # Formulation B
        ρ_gas_face_c = 2.0 * ρ_gas_L_c * ρ_gas_R_c / (ρ_gas_L_c + ρ_gas_R_c)
        J_B_c = -λ * ρ_gas_face_c * (φ_R_c - φ_L_c) / Δx

        # Expanded form: -λ[∂ξ/∂x + (ξ/T)∂T/∂x]
        ∂ξ_∂x_c = (ξ_R_c - ξ_L_c) / Δx   # = -10000  (decreasing toward right)
        ξ_face_c = 0.5 * (ξ_L_c + ξ_R_c)   # = 10
        T_face_c = 0.5 * (T_L_c + T_R_c)    # = 600
        ∂T_∂x_c = (T_R_c - T_L_c) / Δx     # = 400000 (increasing toward right)

        fickian = -λ * ∂ξ_∂x_c
        thermal = -λ * (ξ_face_c / T_face_c) * ∂T_∂x_c

        println("\n=== Combined gradients ===")
        println("  ξ_L = $ξ_L_c, ξ_R = $ξ_R_c kg/m³")
        println("  T_L = $T_L_c, T_R = $T_R_c K")
        println("  p_L = $(round(p_L_c, sigdigits=4)) Pa")
        println("  p_R = $(round(p_R_c, sigdigits=4)) Pa")
        println("  Fickian term (-λ ∂ξ/∂x):     $(round(fickian, sigdigits=4))")
        println("  Thermal term (-λ ξ/T ∂T/∂x): $(round(thermal, sigdigits=4))")
        println("  In this case:")
        if p_L_c > p_R_c
            println("    p_L > p_R → ξ gradient dominates → net flow L→R")
        else
            println("    p_R > p_L → thermal term dominates → net flow R→L")
        end

        println("  J_B = $(round(J_B_c, sigdigits=6)) kg/(m²·s)")

        # The ξ gradient points from high-ξ (L) to low-ξ (R),
        # driving gas to the right (fickian > 0).
        @test fickian > 0.0

        # The thermal term drives gas from hot (R) to cold (L),
        # i.e., to the left (thermal < 0).
        @test thermal < 0.0

        # Net direction depends on which wins.
        # p_L = 15 * R * 400 / M vs p_R = 5 * R * 800 / M
        # p_L/p_R = 15*400 / (5*800) = 6000/4000 = 1.5
        # p_L > p_R, so net flux is L→R (positive)
        @test p_L_c > p_R_c
        # The Fickian term dominates, flux is positive (L to R, down the pressure gradient)
    end

    # ========================================================================
    # Sign convention verification
    # ========================================================================
    @testset "Sign convention: flux direction matches pressure gradient" begin
        # For ANY test case, verify J_B ∝ -(p_R - p_L)
        # i.e., flux is in the direction of DECREASING pressure.

        test_cases = [
            # (ξ_L, ξ_R, T_L, T_R, description)
            (10.0, 10.0, 400.0, 800.0, "equal ξ, T gradient"),
            (20.0, 5.0, 600.0, 600.0, "ξ gradient, uniform T"),
            (10.0, 10.0, 800.0, 400.0, "equal ξ, reversed T gradient"),
            (5.0, 20.0, 400.0, 800.0, "opposing ξ and T gradients"),
        ]

        for (ξ_L_t, ξ_R_t, T_L_t, T_R_t, desc) in test_cases
            p_L_t = ξ_L_t * R_gas * T_L_t / M_gas
            p_R_t = ξ_R_t * R_gas * T_R_t / M_gas

            ρ_gas_L_t = P_atm * M_gas / (R_gas * T_L_t)
            ρ_gas_R_t = P_atm * M_gas / (R_gas * T_R_t)
            φ_L_t = ξ_L_t / ρ_gas_L_t
            φ_R_t = ξ_R_t / ρ_gas_R_t
            ρ_gas_face_t = 2.0 * ρ_gas_L_t * ρ_gas_R_t / (ρ_gas_L_t + ρ_gas_R_t)
            J_B_t = -λ * ρ_gas_face_t * (φ_R_t - φ_L_t) / Δx

            Δp_t = p_R_t - p_L_t

            # Flux should oppose pressure gradient:
            # If Δp > 0 (p_R > p_L), flux should be negative (R→L)
            # If Δp < 0 (p_L > p_R), flux should be positive (L→R)
            if abs(Δp_t) > 1e-10
                @test sign(J_B_t) == -sign(Δp_t)
            end

            println("  $desc: Δp = $(round(Δp_t, sigdigits=4)), J_B = $(round(J_B_t, sigdigits=4)) ✓")
        end
    end
end

